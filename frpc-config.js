// frpc TOML generation for dsh-frp.
//
// Everything the plugin hands to frpc goes through here: the strings are
// escaped by tomlString so a hostile or careless value (a newline in a domain,
// a quote in a token) can never rewrite the document structure, and the only
// non-string values are integers this module validates.

export const FRP_VERSION = '0.72.0';

/**
 * Render a value as a TOML basic string.
 *
 * Escapes backslash, double quote and every control character (including
 * newline, CR, tab and DEL) as \\uXXXX so the result can never terminate its
 * own string or start a new TOML line.
 */
export function tomlString(value) {
  const text = String(value);
  let out = '"';
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (code < 0x20 || code === 0x7f) out += '\\u' + code.toString(16).padStart(4, '0');
    else out += ch;
  }
  return out + '"';
}

/** Six lowercase hex characters, from the CSPRNG, for a per-start proxy name. */
export function randomProxyNameSuffix() {
  const bytes = new Uint8Array(3);
  globalThis.crypto.getRandomValues(bytes);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}

function requirePort(value, label) {
  const port = Number(value);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new TypeError(label + ' must be an integer TCP port, got ' + String(value));
  }
  return port;
}

function requireText(value, label) {
  const text = String(value ?? '');
  if (text.length === 0) throw new TypeError(label + ' must not be empty');
  return text;
}

/**
 * Render the frpc configuration for the single DSH GUI tunnel.
 *
 * @param {object} opts
 * @param {string} opts.serverAddr   frps host
 * @param {number} opts.serverPort   frps bind port
 * @param {string} opts.authToken    frps auth token (from credentials)
 * @param {boolean} opts.useTls      written explicitly either way
 * @param {string} opts.domain       public vhost domain (customDomains entry)
 * @param {number} opts.localPort    gateway loopback port
 * @param {number} opts.adminPort    frpc admin API port
 * @param {string} opts.adminUser    frpc admin API user
 * @param {string} opts.adminPassword frpc admin API password
 * @param {string} opts.proxyName    proxy name (random suffix per start)
 * @returns {string} TOML document
 */
export function renderFrpcToml(opts) {
  const serverAddr = requireText(opts.serverAddr, 'serverAddr');
  const serverPort = requirePort(opts.serverPort, 'serverPort');
  const authToken = requireText(opts.authToken, 'authToken');
  const domain = requireText(opts.domain, 'domain');
  const localPort = requirePort(opts.localPort, 'localPort');
  const adminPort = requirePort(opts.adminPort, 'adminPort');
  const adminUser = requireText(opts.adminUser, 'adminUser');
  const adminPassword = requireText(opts.adminPassword, 'adminPassword');
  const proxyName = requireText(opts.proxyName, 'proxyName');

  const lines = [
    '# Generated by dsh-frp. Rewritten on every start: edits here are lost.',
    'serverAddr = ' + tomlString(serverAddr),
    'serverPort = ' + serverPort,
    'auth.token = ' + tomlString(authToken),
    'transport.tls.enable = ' + (opts.useTls ? 'true' : 'false'),
    // Keep retrying a failed first login instead of exiting: the panel shows
    // the error through the admin API while the tunnel recovers on its own.
    'loginFailExit = false',
    'webServer.addr = "127.0.0.1"',
    'webServer.port = ' + adminPort,
    'webServer.user = ' + tomlString(adminUser),
    'webServer.password = ' + tomlString(adminPassword),
    '',
    '[[proxies]]',
    'type = "http"',
    'customDomains = [' + tomlString(domain) + ']',
    'name = ' + tomlString(proxyName),
    'localIP = "127.0.0.1"',
    'localPort = ' + localPort,
    // A dead gateway drops the route from frps instead of leaving a tunnel that
    // answers 502 forever.
    'healthCheck.type = "tcp"',
    '',
  ];
  return lines.join('\n');
}
